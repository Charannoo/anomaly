                "import faiss\n",
                "from tabulate import tabulate\n",
                "\n",
                "class MemoryBankAnomalyDetector:\n",
                "    def __init__(self, subsample_ratio=0.10, k=9):\n",
                "        self.subsample_ratio = subsample_ratio\n",
                "        self.k = k\n",
                "        self.index = None\n",
                "        \n",
                "    def fit(self, train_features):\n",
                "        feat_np = train_features.astype(np.float32)\n",
                "        n_samples = feat_np.shape[0]\n",
                "        n_subsample = max(100, int(n_samples * self.subsample_ratio))\n",
                "        \n",
                "        indices = np.random.choice(n_samples, n_subsample, replace=False)\n",
                "        coreset = feat_np[indices]\n",
                "        \n",
                "        d = feat_np.shape[1]\n",
                "        self.index = faiss.IndexFlatL2(d)\n",
                "        self.index.add(coreset)\n",
                "        \n",
                "    def predict(self, test_features, patch_h=28, patch_w=28):\n",
                "        N_test, N_patches, D = test_features.shape\n",
                "        flat_test = test_features.reshape(-1, D).astype(np.float32)\n",
                "        \n",
                "        dists, _ = self.index.search(flat_test, self.k)\n",
                "        patch_scores = dists.mean(axis=1).reshape(N_test, N_patches)\n",
                "        img_scores = np.quantile(patch_scores, 0.99, axis=1)\n",
                "        \n",
                "        patch_maps = patch_scores.reshape(N_test, patch_h, patch_w)\n",
                "        maps_resized = []\n",
                "        for i in range(N_test):\n",
                "            t_map = torch.from_numpy(patch_maps[i]).unsqueeze(0).unsqueeze(0).float()\n",
                "            up = nn.functional.interpolate(t_map, size=(224, 224), mode='bilinear', align_corners=False)\n",
                "            maps_resized.append(up.squeeze().numpy())\n",
                "        \n",
                "        return img_scores, np.array(maps_resized)\n",
                "\n",
                "print(\"Memory Bank Engine ready.\")"
