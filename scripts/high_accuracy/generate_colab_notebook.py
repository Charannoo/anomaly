                "    return tiff.imread(path)\n",
                "\n",
                "def resize_organized_pc(organized_pc, target_h=224, target_w=224):\n",
                "    tensor = torch.from_numpy(organized_pc).permute(2, 0, 1).unsqueeze(0).float()\n",
                "    resized = torch.nn.functional.interpolate(tensor, size=(target_h, target_w), mode='nearest')\n",
                "    return resized.squeeze(0).permute(1, 2, 0).numpy()\n",
                "\n",
                "def square_distance(src, dst):\n",
                "    B, N, _ = src.shape\n",
                "    _, S, _ = dst.shape\n",
                "    dist = -2 * torch.matmul(src, dst.permute(0, 2, 1))\n",
                "    dist += torch.sum(src ** 2, -1).view(B, N, 1)\n",
                "    dist += torch.sum(dst ** 2, -1).view(B, 1, S)\n",
                "    return dist\n",
                "\n",
                "def index_points(points, idx):\n",
                "    device = points.device\n",
                "    B = points.shape[0]\n",
                "    view_shape = list(idx.shape)\n",
                "    view_shape[1:] = [1] * (len(view_shape) - 1)\n",
                "    repeat_shape = list(idx.shape)\n",
                "    repeat_shape[0] = 1\n",
                "    batch_indices = torch.arange(B, dtype=torch.long, device=device).view(view_shape).repeat(repeat_shape)\n",
                "    new_points = points[batch_indices, idx, :]\n",
                "    return new_points\n",
                "\n",
                "def chunked_interpolating_points(xyz1, xyz2, points2, chunk_size=30000):\n",
                "    xyz1_p = xyz1.permute(0, 2, 1)\n",
                "    xyz2_p = xyz2.permute(0, 2, 1)\n",
                "    points2_p = points2.permute(0, 2, 1)\n",
                "    B, N, C = xyz1_p.shape\n",
                "    _, S, D = points2_p.shape\n",
                "    \n",
                "    out_parts = []\n",
                "    for start in range(0, N, chunk_size):\n",
                "        end = min(start + chunk_size, N)\n",
                "        xyz1_chunk = xyz1_p[:, start:end, :]\n",
                "        dists = square_distance(xyz1_chunk, xyz2_p)\n",
                "        dists, idx = dists.sort(dim=-1)\n",
                "        dists, idx = dists[:, :, :3], idx[:, :, :3]\n",
                "        dist_recip = 1.0 / (dists + 1e-8)\n",
                "        norm = torch.sum(dist_recip, dim=2, keepdim=True)\n",
                "        weight = dist_recip / norm\n",
                "        pts_chunk = torch.sum(index_points(points2_p, idx) * weight.view(B, end - start, 3, 1), dim=2)\n",
                "        out_parts.append(pts_chunk)\n",
                "    return torch.cat(out_parts, dim=1).permute(0, 2, 1)\n",
                "\n",
